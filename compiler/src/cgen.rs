    #[test]
    fn lambdas_lift_to_static_functions_with_captures() {
        let code = generate(
            "fn f xs:list i64 k:i64 -> list i64\n ex f [1] 1 = [2]\n map lam x + x k xs\nfn g xs:list i64 -> list i64\n ex g [1] = [1]\n map lam x x xs\nfn main -> unit\n print show f [1] 2\n",
        );
        // The lam node of `f` is n17; it captures `k` (boxed from the fast local).
        assert!(code.contains("static AlValue aleph_lam_n17(const AlFn *aleph_self, AlValue *aleph_args, size_t aleph_n);"), "{code}");
        assert!(code.contains(
            "AL_COLD static AlValue aleph_lamslow_n17(const AlFn *aleph_self, AlValue *aleph_args);"
        ));
        assert!(
            code.contains("AlValue aleph_cap_[1] = {aleph_box_i64(l_k)};"),
            "{code}"
        );
        assert!(code.contains("aleph_fnval_lam(aleph_lam_n17, aleph_cap_, 1)"));
        assert!(code.contains("int64_t l_k = aleph_self->captured[0].u.i64;"));
        assert!(code.contains("AlValue l_k = aleph_self->captured[0];"));
        assert!(code.contains("aleph_lam_enter();") && code.contains("aleph_lam_leave();"));
        // No captures: one static AlFn, no arena allocation; the body temps
        // live only in the lifted functions.
        assert!(
            code.contains("static const AlFn aleph_lamref_ = {aleph_lam_n"),
            "{code}"
        );
        assert!(
            code.contains("aleph_fnval_static(&aleph_lamref_)"),
            "{code}"
        );
        let fast_f = &code[code.find("static AlValue aleph_fn_f(").expect("fast f")..];
        let fast_f = &fast_f[..fast_f.find("\n}\n").expect("end of f")];
        assert!(
            !fast_f.contains("t_n18;"),
            "lambda body temps leak into f: {fast_f}"
        );
        // Examples are not compiled, so a lambda there is not lifted.
        let code = generate(
            "fn f -> i64\n ex len map lam x x [1] = 1\n 1\nfn main -> unit\n print show f\n",
        );
        assert!(!code.contains("aleph_lam_n"), "{code}");
    }

