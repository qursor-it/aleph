//! C99 code generator for checked Aleph files (T-018, ADR-0006, ADR-0024,
//! ADR-0025).
//!
//! The emitted program is a thin straight-line wrapper around the Tlön runtime:
//! every expression evaluates into a function-local temporary, arguments are
//! evaluated strictly left to right, and `try` exits through a single function
//! epilogue. Evaluation and call depth are mirrored exactly with
//! `aleph_eval_enter`/`aleph_eval_leave` and `aleph_call_enter`/
//! `aleph_call_leave`, so R004 traps match the interpreter.
//!
//! Function values use one static wrapper (`aleph_ref_<kind>_<name>`) plus a
//! static `const AlFn` per `@f`; the runtime's `aleph_b_map`/`filter`/`fold`
//! invoke the wrapper through `fn->code`. A user-function wrapper enters a call
//! frame exactly like a direct call, while constructor and builtin wrappers do
//! not, mirroring `interp::call_target`. Every callback receives its own
//! `AlFn`: a `lam` (ADR-0037) is lifted to `aleph_lam_n<id>` and reads its
//! captured values from `aleph_self->captured`.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::ast::{self, BinOp, CalleeKind, Capability, Expr, ExprKind, NodeId, StmtKind, UnOp};
use crate::builtins;
use crate::check::{CheckOutput, Type};
use crate::diag::Diagnostic;

/// Emit a deterministic C99 translation unit for a checked file.
///
/// Returns `X003` when the file has no `main`; the build pipeline checks that
/// first, but tests and embedders may call this directly.
pub fn emit(
    file_name: &str,
    file: &ast::File,
    checked: &CheckOutput,
) -> Result<String, Box<Diagnostic>> {
    Generator {
        file_name,
        file,
        checked,
        out: String::new(),
        error: None,
    }
    .run()
}

struct Generator<'a> {
    file_name: &'a str,
    file: &'a ast::File,
    checked: &'a CheckOutput,
    out: String,
    error: Option<Box<Diagnostic>>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RefKind {
    User,
    Ctor,
    Builtin,
}

impl RefKind {
    fn label(self) -> &'static str {
        match self {
            Self::User => "user",
            Self::Ctor => "ctor",
            Self::Builtin => "builtin",
        }
    }

    fn kind_constant(self) -> &'static str {
        match self {
            Self::User => "AL_FN_USER",
            Self::Ctor => "AL_FN_CTOR",
            Self::Builtin => "AL_FN_BUILTIN",
        }
    }
}

struct RefInfo {
    name: String,
    kind: RefKind,
    arity: usize,
}

impl<'a> Generator<'a> {
    fn run(mut self) -> Result<String, Box<Diagnostic>> {
        if !self.file.fns.iter().any(|function| function.name == "main") {
            return Err(Box::new(Diagnostic::error(
                "X003",
                self.file_name,
                0,
                0,
                "no main function",
            )));
        }

        self.out.push_str("/* Generated by aleph build. */\n");
        self.out.push_str("#include \"tlon.h\"\n\n");

        let tables_start = self.out.len();
        self.record_infos();
        self.locations();
        self.literal_tables();
        let tables_end = self.out.len();
        self.forward_declarations();
        self.references();
        for function in &self.file.fns {
            self.function(function);
        }
        for lam in self.lambdas() {
            self.lambda(lam);
        }
        if let Some(error) = self.error.take() {
            return Err(error);
        }
        self.entry();

        self.prune_tables(tables_start, tables_end);
        Ok(self.out)
    }

    /// Drop the record infos and locations that no code refers to, so the C
    /// stays clean under `-Wall -Wextra` (unused-const-variable).
    fn prune_tables(&mut self, start: usize, end: usize) {
        // Tables are only ever used by address (`&L_nN`, `&RI_name`); a use
        // without `&` would drop the table and fail the C build loudly.
        // String literals may contain user text such as "&RI_pt": not references.
        let rest = without_string_literals(&self.out[end..]);
        let locations = used_names(&rest, "&L_n");
        let records = used_names(&rest, "&RI_");
        let kept: String = self.out[start..end]
            .split_inclusive('\n')
            .filter(|line| {
                let first_word = |rest: &str| rest.split(' ').next().unwrap_or("").to_string();
                if let Some(rest) = line.strip_prefix("static const AlLoc L_n") {
                    locations.contains(first_word(rest).as_str())
                } else if let Some(rest) = line.strip_prefix("static const AlRecordInfo RI_") {
                    records.contains(first_word(rest).as_str())
                } else {
                    true
                }
            })
            .collect();
        self.out.replace_range(start..end, &kept);
    }

    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn record_infos(&mut self) {
        if self.file.types.is_empty() {
            return;
        }
        // One info per constructor: a record type, or each sum variant.
        let mut infos = Vec::new();
        for item in &self.file.types {
            if item.variants.is_empty() {
                infos.push((item.name.as_str(), item.fields.len()));
            }
            for variant in &item.variants {
                infos.push((variant.name.as_str(), variant.fields.len()));
            }
        }
        for (name, count) in infos {
            let line = format!(
                "static const AlRecordInfo RI_{name} = {{{}, {count}}};",
                c_string(name)
            );
            self.line(0, &line);
        }
        self.out.push('\n');
    }

    fn locations(&mut self) {
        for function in &self.file.fns {
            self.location(function.id, function.span);
            for example in &function.examples {
                self.walk_location(&example.lhs);
                self.walk_location(&example.rhs);
            }
            for stmt in &function.stmts {
                match &stmt.kind {
                    StmtKind::Let { value, .. } | StmtKind::Do { value } => {
                        self.walk_location(value);
                    }
                    StmtKind::Guard { cond, value } => {
                        self.walk_location(cond);
                        self.walk_location(value);
                    }
                }
            }
            self.walk_location(&function.result);
        }
        self.out.push('\n');
    }

    fn walk_location(&mut self, expr: &Expr) {
        let mut spans = Vec::new();
        ast::walk_expr(expr, &mut |node| spans.push((node.id, node.span)));
        for (id, span) in spans {
            self.location(id, span);
        }
    }

    /// One `static const AlValue` table per list literal whose items are all
    /// i64 or bool literals (T-062). `aleph_list` copies the table into the
    /// arena, so the list itself still lives in the region.
    fn literal_tables(&mut self) {
        let file = self.file;
        let mut tables = Vec::new();
        for function in &file.fns {
            for root in frame_roots(function) {
                ast::walk_expr(root, &mut |expr| {
                    if let Some(items) = literal_list_items(expr) {
                        tables.push((expr.id.0, items.to_vec()));
                    }
                });
            }
        }
        if tables.is_empty() {
            return;
        }
        for (id, items) in tables {
            self.line(0, &format!("static const AlValue aleph_list_n{id}[] = {{"));
            for item in items {
                let entry = match &item.kind {
                    ExprKind::Int { value } => {
                        format!("{{AL_I64, {{.i64 = {}}}}}", int_literal(*value))
                    }
                    ExprKind::Bool { value } => format!("{{AL_BOOL, {{.b = {value}}}}}"),
                    _ => unreachable!("literal_list_items only returns int/bool items"),
                };
                self.line(1, &format!("{entry},"));
            }
            self.line(0, "};");
        }
        self.out.push('\n');
    }

    fn location(&mut self, id: NodeId, span: ast::Span) {
        let line = format!(
            "static const AlLoc L_n{} = {{{}, {}, {}}};",
            id.0, id.0, span.line, span.col
        );
        self.line(0, &line);
    }

    fn forward_declarations(&mut self) {
        for function in &self.file.fns {
            let fast = self.signature(function, "fn", "l_");
            let slow = self.signature(function, "slow", "p_");
            self.line(0, &format!("{fast};"));
            self.line(0, &format!("AL_COLD {slow};"));
        }
        for lam in self.lambdas() {
            let id = lam.id.0;
            self.line(0, &format!("{};", lam_signature(id)));
            self.line(0, &format!("AL_COLD {};", lam_slow_signature(id)));
        }
        self.out.push('\n');
    }

    /// `static R aleph_<prefix>_<name>(T l_a, ...)` with unboxed primitive
    /// parameter and return types (ADR-0027).
    fn signature(&self, function: &ast::Fn, prefix: &str, param_prefix: &str) -> String {
        let (params, ret) = self.fn_types(&function.name);
        let mut signature = format!(
            "static {} aleph_{prefix}_{}(",
            Repr::of(&ret).c_type(),
            function.name
        );
        if function.params.is_empty() {
            signature.push_str("void");
        } else {
            let list: Vec<String> = function
                .params
                .iter()
                .zip(&params)
                .map(|(param, ty)| {
                    format!("{} {param_prefix}{}", Repr::of(ty).c_type(), param.name)
                })
                .collect();
            signature.push_str(&list.join(", "));
        }
        signature.push(')');
        signature
    }

    fn fn_types(&self, name: &str) -> (Vec<Type>, Type) {
        self.checked
            .signatures
            .get(name)
            .cloned()
            .expect("checker records a signature for every function")
    }

    fn used_refs(&self) -> Vec<RefInfo> {
        let mut names = BTreeSet::new();
        let mut visit = |expr: &Expr| {
            if let ExprKind::FnRef { name } = &expr.kind {
                names.insert(name.clone());
            }
        };
        for function in &self.file.fns {
            for stmt in &function.stmts {
                match &stmt.kind {
                    StmtKind::Let { value, .. } | StmtKind::Do { value } => {
                        ast::walk_expr(value, &mut visit);
                    }
                    StmtKind::Guard { cond, value } => {
                        ast::walk_expr(cond, &mut visit);
                        ast::walk_expr(value, &mut visit);
                    }
                }
            }
            ast::walk_expr(&function.result, &mut visit);
        }
        names.into_iter().map(|name| self.ref_info(&name)).collect()
    }

    fn ref_info(&self, name: &str) -> RefInfo {
        if let Some(function) = self.file.fns.iter().find(|function| function.name == name) {
            return RefInfo {
                name: name.to_string(),
                kind: RefKind::User,
                arity: function.params.len(),
            };
        }
        if let Some(fields) = self.checked.records.get(name) {
            return RefInfo {
                name: name.to_string(),
                kind: RefKind::Ctor,
                arity: fields.len(),
            };
        }
        let spec = builtins::lookup(name).expect("checker guarantees a callable");
        RefInfo {
            name: name.to_string(),
            kind: RefKind::Builtin,
            arity: spec.arity(),
        }
    }

    fn references(&mut self) {
        let references = self.used_refs();
        for reference in &references {
            self.reference_wrapper(reference);
        }
        if !references.is_empty() {
            self.out.push('\n');
        }
        for reference in &references {
            let label = reference.kind.label();
            let name = &reference.name;
            self.line(
                0,
                &format!(
                    "static const AlFn aleph_fnref_{label}_{name} = {{aleph_ref_{label}_{name}, {}, {}, NULL, 0}};",
                    c_string(name),
                    reference.kind.kind_constant()
                ),
            );
        }
        if !references.is_empty() {
            self.out.push('\n');
        }
    }

    fn reference_wrapper(&mut self, reference: &RefInfo) {
        let label = reference.kind.label();
        let name = &reference.name;
        self.line(
            0,
            &format!(
                "static AlValue aleph_ref_{label}_{name}(const AlFn *aleph_self, AlValue *aleph_args, size_t aleph_n)"
            ),
        );
        self.line(0, "{");
        self.line(1, "AlValue aleph_ret_;");
        self.line(1, "(void)aleph_self;");
        self.line(1, "(void)aleph_n;");
        if reference.arity == 0 {
            self.line(1, "(void)aleph_args;");
        }
        let call_args = (0..reference.arity)
            .map(|index| format!("aleph_args[{index}]"))
            .collect::<Vec<_>>()
            .join(", ");
        match reference.kind {
            RefKind::User => {
                let (params, ret) = self.fn_types(name);
                let args = params
                    .iter()
                    .enumerate()
                    .map(|(index, ty)| Repr::of(ty).unbox(&format!("aleph_args[{index}]")))
                    .collect::<Vec<_>>()
                    .join(", ");
                let call = Repr::of(&ret).boxed(&format!("aleph_fn_{name}({args})"));
                self.line(1, "aleph_call_enter(NULL);");
                self.line(1, &format!("aleph_ret_ = {call};"));
                self.line(1, "aleph_call_leave();");
            }
            RefKind::Ctor => {
                if reference.arity == 0 {
                    self.line(
                        1,
                        &format!("aleph_ret_ = aleph_record(&RI_{name}, NULL, 0);"),
                    );
                } else {
                    self.line(
                        1,
                        &format!(
                            "aleph_ret_ = aleph_record(&RI_{name}, aleph_args, {});",
                            reference.arity
                        ),
                    );
                }
            }
            RefKind::Builtin => {
                let call = if name == "cat" {
                    format!(
                        "aleph_args[0].tag == AL_LIST ? aleph_b_catl({call_args}) : aleph_b_cat({call_args})"
                    )
                } else {
                    format!("aleph_b_{name}({call_args})")
                };
                self.line(1, &format!("aleph_ret_ = {call};"));
            }
        }
        self.line(1, "return aleph_ret_;");
        self.line(0, "}");
    }

    fn function(&mut self, function: &ast::Fn) {
        self.slow_function(function);
        self.fast_function(function);
    }

    /// Instrumented body mirroring `interp.rs` node by node (ADR-0025). Taken
    /// only when the fast body could reach the evaluation-depth limit.
    fn slow_function(&mut self, function: &ast::Fn) {
        let (params, ret) = self.fn_types(&function.name);
        let signature = self.signature(function, "slow", "p_");
        self.line(0, &signature);
        self.line(0, "{");
        for (param, ty) in function.params.iter().zip(&params) {
            let value = Repr::of(ty).boxed(&format!("p_{}", param.name));
            let name = &param.name;
            self.line(1, &format!("AlValue l_{name} = {value}; (void)l_{name};"));
        }

        self.slow_declarations(function_declarations(function));
        for stmt in &function.stmts {
            if let StmtKind::Let { name, .. } = &stmt.kind {
                self.line(1, &format!("AlValue l_{name};"));
            }
        }
        self.line(1, "AlValue aleph_ret_;");
        self.region_mark(function);
        self.line(1, "aleph_ret_ = aleph_unit();");

        for stmt in &function.stmts {
            match &stmt.kind {
                StmtKind::Let { name, value } => {
                    self.emit_expr(value, 0, 1);
                    // `(void)` keeps an unused binder from warning under -Wall.
                    self.line(
                        1,
                        &format!("l_{name} = t_n{0}; (void)l_{name};", value.id.0),
                    );
                }
                StmtKind::Do { value } => {
                    self.emit_expr(value, 0, 1);
                    self.line(1, &format!("(void)t_n{};", value.id.0));
                }
                StmtKind::Guard { cond, value } => {
                    self.emit_expr(cond, 0, 1);
                    self.line(1, &format!("if (t_n{}.u.b) {{", cond.id.0));
                    self.emit_expr(value, 0, 2);
                    self.line(2, &format!("aleph_ret_ = t_n{};", value.id.0));
                    self.line(2, "goto L_epilogue;");
                    self.line(1, "}");
                }
            }
        }

        self.emit_expr(&function.result, 0, 1);
        self.line(1, &format!("aleph_ret_ = t_n{};", function.result.id.0));
        if function_needs_epilogue(function) {
            self.line(0, "L_epilogue:");
        }
        self.region_exit(function, Repr::Boxed);
        self.line(
            1,
            &format!("return {};", Repr::of(&ret).unbox("aleph_ret_")),
        );
        self.line(0, "}");
        self.out.push('\n');
    }

    /// Scoped region of a user function body (ADR-0039); `main` has none,
    /// nor has a body that cannot allocate in the arena.
    fn region_mark(&mut self, function: &ast::Fn) {
        if self.needs_region(function) {
            self.line(1, "AlMark aleph_mark_ = aleph_region_mark();");
        }
    }

    fn region_exit(&mut self, function: &ast::Fn, repr: Repr) {
        if !self.needs_region(function) {
            return;
        }
        if repr == Repr::Boxed {
            self.line(
                1,
                "aleph_ret_ = aleph_region_exit(aleph_mark_, aleph_ret_);",
            );
        } else {
            self.line(1, "aleph_region_reset(aleph_mark_);");
        }
    }

    /// Conservative: a body needs no region when every node is an unboxed
    /// i64/f64/bool literal, variable, operator, `if` or call to a user
    /// function (callees reset their own regions).
    fn needs_region(&self, function: &ast::Fn) -> bool {
        if function.name == "main" {
            return false;
        }
        let mut roots: Vec<&Expr> = function
            .stmts
            .iter()
            .flat_map(|stmt| match &stmt.kind {
                StmtKind::Let { value, .. } | StmtKind::Do { value } => vec![value],
                StmtKind::Guard { cond, value } => vec![cond, value],
            })
            .collect();
        roots.push(&function.result);
        self.may_allocate(&roots)
    }

    fn may_allocate(&self, roots: &[&Expr]) -> bool {
        let mut allocates = false;
        let mut visit = |expr: &Expr| {
            let plain = matches!(
                expr.kind,
                ExprKind::Int { .. }
                    | ExprKind::Float { .. }
                    | ExprKind::Bool { .. }
                    | ExprKind::Var { .. }
                    | ExprKind::BinOp { .. }
                    | ExprKind::UnOp { .. }
                    | ExprKind::If { .. }
                    | ExprKind::Call {
                        callee_kind: CalleeKind::Fn,
                        ..
                    }
            );
            if !plain || self.repr(expr) == Repr::Boxed {
                allocates = true;
            }
        };
        for root in roots {
            ast::walk_expr(root, &mut visit);
        }
        allocates
    }

    fn emit_expr(&mut self, expr: &Expr, depth: usize, indent: usize) {
        let id = expr.id.0;
        self.line(indent, &format!("aleph_eval_enter(&L_n{id});"));

        match &expr.kind {
            ExprKind::Int { value } => {
                self.assign(indent, id, &format!("aleph_i64({})", int_literal(*value)));
            }
            ExprKind::Float { value } => {
                let bits = value
                    .parse::<f64>()
                    .expect("the lexer validates float syntax")
                    .to_bits();
                self.assign(
                    indent,
                    id,
                    &format!("aleph_f64_bits(UINT64_C(0x{bits:016x}))"),
                );
            }
            ExprKind::Str { value } => {
                self.assign(
                    indent,
                    id,
                    &format!("aleph_str_n({}, {})", c_string(value), value.len()),
                );
            }
            ExprKind::Bool { value } => {
                self.assign(indent, id, &format!("aleph_bool({value})"));
            }
            ExprKind::Nil => self.assign(indent, id, "aleph_unit()"),
            ExprKind::Var { name } => {
                self.assign(indent, id, &format!("l_{name}"));
            }
            ExprKind::FnRef { name } => {
                let info = self.ref_info(name);
                let label = info.kind.label();
                self.assign(
                    indent,
                    id,
                    &format!("aleph_fnval_static(&aleph_fnref_{label}_{name})"),
                );
            }
            ExprKind::Call {
                callee,
                callee_kind,
                args,
            } => {
                for arg in args {
                    self.emit_expr(arg, depth + 1, indent);
                }
                match callee_kind {
                    CalleeKind::Fn => {
                        let (params, ret) = self.fn_types(callee);
                        let call_args = args
                            .iter()
                            .zip(&params)
                            .map(|(arg, ty)| Repr::of(ty).unbox(&format!("t_n{}", arg.id.0)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        let call = Repr::of(&ret).boxed(&format!("aleph_fn_{callee}({call_args})"));
                        self.line(indent, &format!("aleph_call_enter(&L_n{id});"));
                        self.assign(indent, id, &call);
                        self.line(indent, "aleph_call_leave();");
                    }
                    CalleeKind::Ctor => {
                        if args.is_empty() {
                            self.assign(
                                indent,
                                id,
                                &format!("aleph_record(&RI_{callee}, NULL, 0)"),
                            );
                        } else {
                            self.assign(indent, id, &format!("aleph_list_new({})", args.len()));
                            for (index, arg) in args.iter().enumerate() {
                                self.line(
                                    indent,
                                    &format!("t_n{id}.u.list->items[{index}] = t_n{};", arg.id.0),
                                );
                            }
                            self.assign(
                                indent,
                                id,
                                &format!(
                                    "aleph_record(&RI_{callee}, t_n{id}.u.list->items, {})",
                                    args.len()
                                ),
                            );
                        }
                    }
                    CalleeKind::Builtin => {
                        let runtime = self.builtin_c_name(callee, expr);
                        self.assign(
                            indent,
                            id,
                            &format!("aleph_b_{}({})", runtime, arg_list(args)),
                        );
                    }
                }
            }
            ExprKind::BinOp { op, lhs, rhs } => {
                self.emit_expr(lhs, depth + 1, indent);
                match op {
                    BinOp::And | BinOp::Or => {
                        let condition = if *op == BinOp::And {
                            format!("!t_n{}.u.b", lhs.id.0)
                        } else {
                            format!("t_n{}.u.b", lhs.id.0)
                        };
                        self.line(indent, &format!("if ({condition}) {{"));
                        self.assign(indent + 1, id, &format!("t_n{}", lhs.id.0));
                        self.line(indent, "} else {");
                        self.emit_expr(rhs, depth + 1, indent + 1);
                        self.assign(indent + 1, id, &format!("t_n{}", rhs.id.0));
                        self.line(indent, "}");
                    }
                    _ => {
                        self.emit_expr(rhs, depth + 1, indent);
                        let value = self.binop_value(expr, *op, lhs, rhs);
                        self.assign(indent, id, &value);
                    }
                }
            }
            ExprKind::UnOp { op, operand } => {
                self.emit_expr(operand, depth + 1, indent);
                let value = match op {
                    UnOp::Not => format!("aleph_bool(!t_n{}.u.b)", operand.id.0),
                    UnOp::Neg => match self.concrete_type(expr) {
                        Some(Type::F64) => format!("aleph_f64(-t_n{}.u.f64)", operand.id.0),
                        Some(Type::I64) => format!("aleph_neg_i64(t_n{})", operand.id.0),
                        Some(_) => {
                            self.fail_internal(
                                expr,
                                "internal compiler error: non-numeric negation",
                            );
                            "aleph_unit()".to_string()
                        }
                        None => "aleph_unit()".to_string(),
                    },
                };
                self.assign(indent, id, &value);
            }
            ExprKind::If { cond, then_, else_ } => {
                self.emit_expr(cond, depth + 1, indent);
                self.line(indent, &format!("if (t_n{}.u.b) {{", cond.id.0));
                self.emit_expr(then_, depth + 1, indent + 1);
                self.assign(indent + 1, id, &format!("t_n{}", then_.id.0));
                self.line(indent, "} else {");
                self.emit_expr(else_, depth + 1, indent + 1);
                self.assign(indent + 1, id, &format!("t_n{}", else_.id.0));
                self.line(indent, "}");
            }
            ExprKind::List { elems } => {
                if let Some(items) = literal_list_items(expr) {
                    // The interpreter evaluates each item in a child frame;
                    // literal items cannot trap except by depth, and all sit
                    // at the same depth, so one frame of the first item
                    // reproduces the R004 trap and its location.
                    self.line(indent, &format!("aleph_eval_enter(&L_n{});", items[0].id.0));
                    self.line(indent, "aleph_eval_leave();");
                    self.assign(
                        indent,
                        id,
                        &format!("aleph_list(aleph_list_n{id}, {})", elems.len()),
                    );
                } else {
                    for elem in elems {
                        self.emit_expr(elem, depth + 1, indent);
                    }
                    self.assign(indent, id, &format!("aleph_list_new({})", elems.len()));
                    for (index, elem) in elems.iter().enumerate() {
                        self.line(
                            indent,
                            &format!("t_n{id}.u.list->items[{index}] = t_n{};", elem.id.0),
                        );
                    }
                }
            }
            ExprKind::Empty { .. } | ExprKind::EmptyList => {
                self.assign(indent, id, "aleph_list_new(0)")
            }
            ExprKind::Dict { .. } => self.assign(indent, id, "aleph_dict_empty()"),
            ExprKind::Field { name, value } => {
                self.emit_expr(value, depth + 1, indent);
                let index = self.field_index(value, name);
                self.assign(
                    indent,
                    id,
                    &format!("t_n{}.u.rec->fields[{index}]", value.id.0),
                );
            }
            ExprKind::Some { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.assign(indent, id, &format!("aleph_some(t_n{})", value.id.0));
            }
            ExprKind::None { .. } => self.assign(indent, id, "aleph_none()"),
            ExprKind::Ok { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.assign(indent, id, &format!("aleph_ok(t_n{})", value.id.0));
            }
            ExprKind::Err { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.assign(indent, id, &format!("aleph_err(t_n{})", value.id.0));
            }
            ExprKind::Try { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.line(indent, &format!("if (t_n{}.tag == AL_OK) {{", value.id.0));
                self.assign(indent + 1, id, &format!("t_n{}.u.box->value", value.id.0));
                self.line(indent, "} else {");
                for _ in 0..=depth {
                    self.line(indent + 1, "aleph_eval_leave();");
                }
                self.line(indent + 1, &format!("aleph_ret_ = t_n{};", value.id.0));
                self.line(indent + 1, "goto L_epilogue;");
                self.line(indent, "}");
            }
            ExprKind::Else { value, default } => {
                self.emit_expr(value, depth + 1, indent);
                let tag = self.else_tag(value);
                self.line(indent, &format!("if (t_n{}.tag == {tag}) {{", value.id.0));
                self.assign(indent + 1, id, &format!("t_n{}.u.box->value", value.id.0));
                self.line(indent, "} else {");
                self.emit_expr(default, depth + 1, indent + 1);
                self.assign(indent + 1, id, &format!("t_n{}", default.id.0));
                self.line(indent, "}");
            }
            ExprKind::Has { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.assign(
                    indent,
                    id,
                    &format!("aleph_bool(t_n{}.tag == AL_SOME)", value.id.0),
                );
            }
            ExprKind::IsOk { value } => {
                self.emit_expr(value, depth + 1, indent);
                self.assign(
                    indent,
                    id,
                    &format!("aleph_bool(t_n{}.tag == AL_OK)", value.id.0),
                );
            }
            ExprKind::Lam { .. } => self.closure(expr, false, indent),
            ExprKind::Match { value, arms } => {
                self.emit_expr(value, depth + 1, indent);
                for (index, arm) in arms.iter().enumerate() {
                    self.match_arm_open(value, arms.len(), index, &arm.variant, indent);
                    for (k, binder) in arm.binders.iter().enumerate() {
                        let field = format!("t_n{}.u.rec->fields[{k}]", value.id.0);
                        // `(void)` keeps an unused binder from warning under -Wall.
                        self.line(
                            indent + 1,
                            &format!("AlValue l_{binder} = {field}; (void)l_{binder};"),
                        );
                    }
                    self.emit_expr(&arm.body, depth + 1, indent + 1);
                    self.assign(indent + 1, id, &format!("t_n{}", arm.body.id.0));
                }
                self.line(indent, "}");
            }
        }

        self.line(indent, "aleph_eval_leave();");
    }

    /// Open the C block of arm `index`: dispatch on the record info pointer;
    /// the last arm is the plain `else` (the checker makes `match` exhaustive).
    fn match_arm_open(
        &mut self,
        value: &Expr,
        count: usize,
        index: usize,
        variant: &str,
        indent: usize,
    ) {
        let test = format!("if (t_n{}.u.rec->info == &RI_{variant}) {{", value.id.0);
        let text = match (index, index + 1 == count) {
            (0, true) => "{".to_string(),
            (0, false) => test,
            (_, true) => "} else {".to_string(),
            (_, false) => format!("}} else {test}"),
        };
        self.line(indent, &text);
    }

    fn assign(&mut self, indent: usize, id: u32, value: &str) {
        self.line(indent, &format!("t_n{id} = {value};"));
    }

    fn binop_value(&mut self, expr: &Expr, op: BinOp, lhs: &Expr, rhs: &Expr) -> String {
        let left = format!("t_n{}", lhs.id.0);
        let right = format!("t_n{}", rhs.id.0);
        let value = match op {
            BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div => match self.concrete_type(expr) {
                Some(Type::F64) => {
                    let symbol = match op {
                        BinOp::Add => "+",
                        BinOp::Sub => "-",
                        BinOp::Mul => "*",
                        _ => "/",
                    };
                    format!("aleph_f64({left}.u.f64 {symbol} {right}.u.f64)")
                }
                Some(Type::I64) => {
                    let function = match op {
                        BinOp::Add => "aleph_add_i64",
                        BinOp::Sub => "aleph_sub_i64",
                        BinOp::Mul => "aleph_mul_i64",
                        _ => "aleph_div_i64",
                    };
                    format!("{function}({left}, {right})")
                }
                Some(_) => {
                    self.fail_internal(expr, "internal compiler error: non-numeric arithmetic");
                    "aleph_unit()".to_string()
                }
                None => "aleph_unit()".to_string(),
            },
            BinOp::Mod => format!("aleph_mod_i64({left}, {right})"),
            BinOp::Eq => format!("aleph_bool(aleph_values_equal({left}, {right}))"),
            BinOp::Ne => format!("aleph_bool(!aleph_values_equal({left}, {right}))"),
            BinOp::Lt => format!("aleph_bool(aleph_lt({left}, {right}))"),
            BinOp::Le => format!("aleph_bool(aleph_le({left}, {right}))"),
            BinOp::Gt => format!("aleph_bool(aleph_gt({left}, {right}))"),
            BinOp::Ge => format!("aleph_bool(aleph_ge({left}, {right}))"),
            BinOp::And | BinOp::Or => unreachable!("handled by emit_expr"),
        };
        value
    }

    fn field_index(&mut self, base: &Expr, name: &str) -> usize {
        match self.concrete_type(base) {
            Some(Type::Record(record)) => self
                .checked
                .records
                .get(&record)
                .and_then(|fields| fields.iter().position(|(field, _)| field == name))
                .unwrap_or_else(|| {
                    self.fail_internal(base, "internal compiler error: unknown record field");
                    0
                }),
            Some(_) => {
                self.fail_internal(base, "internal compiler error: field access on non-record");
                0
            }
            None => 0,
        }
    }

    fn else_tag(&mut self, value: &Expr) -> &'static str {
        match self.concrete_type(value) {
            Some(Type::Opt(_)) => "AL_SOME",
            Some(Type::Res(_, _)) => "AL_OK",
            Some(_) => {
                self.fail_internal(value, "internal compiler error: else on non-opt/non-res");
                "AL_NONE"
            }
            None => "AL_NONE",
        }
    }

    fn concrete_type(&mut self, expr: &Expr) -> Option<Type> {
        match self.checked.expr_types.get(&expr.id) {
            Some(Type::Var(_)) | Some(Type::Error) | None => {
                self.fail_internal(expr, "internal compiler error: unresolved expression type");
                None
            }
            Some(ty) => Some(ty.clone()),
        }
    }

    fn fail_internal(&mut self, expr: &Expr, msg: &str) {
        if self.error.is_none() {
            self.error = Some(Box::new(
                Diagnostic::error("X006", self.file_name, expr.span.line, expr.span.col, msg)
                    .with_node(format!("n{}", expr.id.0)),
            ));
        }
    }

    fn entry(&mut self) {
        let main = self
            .file
            .fns
            .iter()
            .find(|function| function.name == "main")
            .expect("run checked for main");

        self.line(
            0,
            "static AlValue aleph_entry(AlValue *aleph_args, size_t aleph_count)",
        );
        self.line(0, "{");
        self.line(1, "AlValue aleph_value;");
        self.line(1, "(void)aleph_args;");
        self.line(1, "(void)aleph_count;");
        // Keep functions that nothing calls from warning (unused-function).
        for function in &self.file.fns {
            if function.name != "main" {
                self.line(1, &format!("(void)aleph_fn_{};", function.name));
            }
        }
        self.line(1, &format!("aleph_call_enter(&L_n{});", main.id.0));
        let (_, main_ret) = self.fn_types("main");
        let call = Repr::of(&main_ret).boxed("aleph_fn_main()");
        self.line(1, &format!("aleph_value = {call};"));
        self.line(1, "aleph_call_leave();");
        self.line(1, "return aleph_value;");
        self.line(0, "}");
        self.out.push('\n');

        let uses: Vec<(&str, &str)> = self
            .file
            .uses
            .iter()
            .filter_map(|item| {
                let cap = match item.cap {
                    Capability::FsRead => "AL_CAP_FS_READ",
                    Capability::FsWrite => "AL_CAP_FS_WRITE",
                    Capability::NetHost => "AL_CAP_NET_HOST",
                    Capability::Env | Capability::Time => return None,
                };
                item.path.as_deref().map(|path| (cap, path))
            })
            .collect();
        if !uses.is_empty() {
            self.line(0, "static const AlUse aleph_uses[] = {");
            for (cap, path) in &uses {
                self.line(1, &format!("{{{cap}, {}}},", c_string(path)));
            }
            self.line(0, "};");
            self.out.push('\n');
        }

        self.line(0, "int main(int argc, char **argv)");
        self.line(0, "{");
        self.line(1, &format!("aleph_set_file({});", c_string(self.file_name)));
        if uses.is_empty() {
            self.line(1, "aleph_set_uses(NULL, 0);");
        } else {
            self.line(1, &format!("aleph_set_uses(aleph_uses, {});", uses.len()));
        }
        self.line(
            1,
            "return aleph_main_run(aleph_entry, argc > 0 ? argc - 1 : 0, argc > 0 ? (const char *const *)(argv + 1) : NULL);",
        );
        self.line(0, "}");
    }
}

/// C representation of an Aleph value in the fast path (ADR-0027): `i64`,
/// `f64` and `bool` are unboxed C scalars, everything else stays an `AlValue`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Repr {
    I64,
    F64,
    Bool,
    Boxed,
}

impl Repr {
    fn of(ty: &Type) -> Self {
        match ty {
            Type::I64 => Self::I64,
            Type::F64 => Self::F64,
            Type::Bool => Self::Bool,
            _ => Self::Boxed,
        }
    }

    fn c_type(self) -> &'static str {
        match self {
            Self::I64 => "int64_t",
            Self::F64 => "double",
            Self::Bool => "bool",
            Self::Boxed => "AlValue",
        }
    }

    /// Wrap a C expression of this representation into an `AlValue`.
    fn boxed(self, value: &str) -> String {
        match self {
            Self::I64 => format!("aleph_box_i64({value})"),
            Self::F64 => format!("aleph_box_f64({value})"),
            Self::Bool => format!("aleph_box_bool({value})"),
            Self::Boxed => value.to_string(),
        }
    }

    /// Read an `AlValue` C expression as this representation.
    fn unbox(self, value: &str) -> String {
        match self {
            Self::I64 => format!("{value}.u.i64"),
            Self::F64 => format!("{value}.u.f64"),
            Self::Bool => format!("{value}.u.b"),
            Self::Boxed => value.to_string(),
        }
    }
}

/// Frames a user call or higher-order builtin adds below the caller's root:
/// the call node itself is at `depth`, the interpreter has `depth + 1` frames
/// open while it runs and the callee body starts at `depth + 2`.
fn calls_back(name: &str) -> bool {
    builtins::lookup(name)
        .map(|spec| {
            spec.params
                .iter()
                .any(|ty| matches!(ty, builtins::Ty::Fn(..)))
        })
        .unwrap_or(false)
}

/// Deepest evaluation frame a function body can open, relative to its root,
/// counting the `+1` frame that a user call or callback check sees.
fn max_eval_depth(function: &ast::Fn) -> usize {
    frame_roots(function).map(expr_max_depth).max().unwrap_or(0)
}

/// [`max_eval_depth`] for one root expression (a statement, result or lambda
/// body).
fn expr_max_depth(root: &Expr) -> usize {
    fn walk(expr: &Expr, depth: usize, max: &mut usize) {
        *max = (*max).max(depth);
        if let ExprKind::Call {
            callee,
            callee_kind,
            ..
        } = &expr.kind
        {
            let checks_on_call = match callee_kind {
                CalleeKind::Fn => true,
                CalleeKind::Builtin => calls_back(callee),
                CalleeKind::Ctor => false,
            };
            if checks_on_call {
                *max = (*max).max(depth + 1);
            }
        }
        for child in children(expr) {
            walk(child, depth + 1, max);
        }
    }
    let mut max = 0;
    walk(root, 0, &mut max);
    max
}

/// The statement values and the result of a function, in order.
fn frame_roots(function: &ast::Fn) -> impl Iterator<Item = &Expr> {
    function
        .stmts
        .iter()
        .flat_map(|stmt| match &stmt.kind {
            StmtKind::Let { value, .. } | StmtKind::Do { value } => vec![value],
            StmtKind::Guard { cond, value } => vec![cond, value],
        })
        .chain([&function.result])
}

/// Ids of the nodes evaluated in the frame of `root`, pre-order, without the
/// bodies of lambdas (each is lifted to its own C function).
fn frame_nodes(root: &Expr, ids: &mut Vec<NodeId>) {
    ids.push(root.id);
    // A compact literal list has no per-item temporaries (T-062).
    if literal_list_items(root).is_some() {
        return;
    }
    for child in children(root) {
        frame_nodes(child, ids);
    }
}

/// Items of a list literal that can become one static `AlValue` table: a
/// non-empty list whose items are all i64 literals or all bool literals.
fn literal_list_items(expr: &Expr) -> Option<&[Expr]> {
    let ExprKind::List { elems } = &expr.kind else {
        return None;
    };
    if elems.is_empty() {
        return None;
    }
    let all_int = elems
        .iter()
        .all(|item| matches!(item.kind, ExprKind::Int { .. }));
    let all_bool = elems
        .iter()
        .all(|item| matches!(item.kind, ExprKind::Bool { .. }));
    (all_int || all_bool).then_some(elems.as_slice())
}

/// Direct sub-expressions, in evaluation order.
fn children(expr: &Expr) -> Vec<&Expr> {
    match &expr.kind {
        ExprKind::Call { args, .. } => args.iter().collect(),
        ExprKind::BinOp { lhs, rhs, .. } => vec![lhs, rhs],
        ExprKind::UnOp { operand, .. } => vec![operand],
        ExprKind::If { cond, then_, else_ } => vec![cond, then_, else_],
        ExprKind::List { elems } => elems.iter().collect(),
        ExprKind::Field { value, .. }
        | ExprKind::Some { value }
        | ExprKind::Ok { value }
        | ExprKind::Err { value }
        | ExprKind::Try { value }
        | ExprKind::Has { value }
        | ExprKind::IsOk { value } => vec![value],
        ExprKind::Else { value, default } => vec![value, default],
        ExprKind::Match { value, arms } => std::iter::once(&**value)
            .chain(arms.iter().map(|arm| &arm.body))
            .collect(),
        // A lambda body runs in its own frame when called, not here.
        ExprKind::Lam { .. }
        | ExprKind::Int { .. }
        | ExprKind::Float { .. }
        | ExprKind::Str { .. }
        | ExprKind::Bool { .. }
        | ExprKind::Nil
        | ExprKind::Var { .. }
        | ExprKind::FnRef { .. }
        | ExprKind::Empty { .. }
        | ExprKind::EmptyList
        | ExprKind::Dict { .. }
        | ExprKind::None { .. } => Vec::new(),
    }
}

impl Generator<'_> {
    /// Unboxed body without per-node depth accounting (ADR-0027). It falls back
    /// to `aleph_slow_<name>` when its static maximum depth could reach the
    /// R004 evaluation limit, so traps stay identical to the interpreter.
    fn fast_function(&mut self, function: &ast::Fn) {
        let (_, ret) = self.fn_types(&function.name);
        let signature = self.signature(function, "fn", "l_");
        let max_depth = max_eval_depth(function);
        self.line(0, &signature);
        self.line(0, "{");
        let forward = function
            .params
            .iter()
            .map(|param| format!("l_{}", param.name))
            .collect::<Vec<_>>()
            .join(", ");
        self.line(
            1,
            &format!("if (AL_UNLIKELY(!aleph_fast_ok({max_depth}))) {{"),
        );
        self.line(
            2,
            &format!("return aleph_slow_{}({forward});", function.name),
        );
        self.line(1, "}");

        let mut declarations = Vec::new();
        for root in frame_roots(function) {
            frame_nodes(root, &mut declarations);
        }
        self.fast_declarations(declarations);
        for stmt in &function.stmts {
            if let StmtKind::Let { name, value } = &stmt.kind {
                let repr = self.repr_of_id(value.id);
                self.line(1, &format!("{} l_{name};", repr.c_type()));
            }
        }
        let ret_repr = Repr::of(&ret);
        self.line(1, &format!("{} aleph_ret_;", ret_repr.c_type()));
        self.line(1, "aleph_loc_push();");
        self.region_mark(function);

        for stmt in &function.stmts {
            match &stmt.kind {
                StmtKind::Let { name, value } => {
                    self.fast_expr(value, 0, 1);
                    self.line(
                        1,
                        &format!("l_{name} = t_n{0}; (void)l_{name};", value.id.0),
                    );
                }
                StmtKind::Do { value } => {
                    self.fast_expr(value, 0, 1);
                    self.line(1, &format!("(void)t_n{};", value.id.0));
                }
                StmtKind::Guard { cond, value } => {
                    self.fast_expr(cond, 0, 1);
                    self.line(1, &format!("if ({}) {{", Self::temp(cond)));
                    self.fast_expr(value, 0, 2);
                    self.line(2, &format!("aleph_ret_ = {};", Self::temp(value)));
                    self.line(2, "goto L_epilogue;");
                    self.line(1, "}");
                }
            }
        }
        self.fast_expr(&function.result, 0, 1);
        self.line(1, &format!("aleph_ret_ = t_n{};", function.result.id.0));
        if function_needs_epilogue(function) {
            self.line(0, "L_epilogue:");
        }
        self.region_exit(function, ret_repr);
        self.line(1, "aleph_loc_pop();");
        self.line(1, "return aleph_ret_;");
        self.line(0, "}");
        self.out.push('\n');
    }

    fn repr_of_id(&self, id: NodeId) -> Repr {
        self.checked
            .expr_types
            .get(&id)
            .map(Repr::of)
            .unwrap_or(Repr::Boxed)
    }

    fn repr(&self, expr: &Expr) -> Repr {
        self.repr_of_id(expr.id)
    }

    fn temp(expr: &Expr) -> String {
        format!("t_n{}", expr.id.0)
    }

    /// `cat` runs on strings or lists; the checked result type picks the
    /// runtime function (ADR-0045).
    fn builtin_c_name(&self, callee: &str, call: &Expr) -> String {
        if callee == "cat" && matches!(self.checked.expr_types.get(&call.id), Some(Type::List(_))) {
            "catl".to_string()
        } else {
            callee.to_string()
        }
    }

    fn boxed_temp(&self, expr: &Expr) -> String {
        self.repr(expr).boxed(&Self::temp(expr))
    }

    fn fast_expr(&mut self, expr: &Expr, depth: usize, indent: usize) {
        let id = expr.id.0;
        let repr = self.repr(expr);
        match &expr.kind {
            ExprKind::Int { value } => self.assign(indent, id, &int_literal(*value)),
            ExprKind::Float { value } => {
                let bits = value
                    .parse::<f64>()
                    .expect("the lexer validates float syntax")
                    .to_bits();
                self.assign(
                    indent,
                    id,
                    &format!("aleph_f64_from_bits(UINT64_C(0x{bits:016x}))"),
                );
            }
            ExprKind::Bool { value } => self.assign(indent, id, &value.to_string()),
            ExprKind::Var { name } => self.assign(indent, id, &format!("l_{name}")),
            ExprKind::Str { .. }
            | ExprKind::Nil
            | ExprKind::FnRef { .. }
            | ExprKind::Empty { .. }
            | ExprKind::EmptyList
            | ExprKind::Dict { .. }
            | ExprKind::None { .. } => {
                // Leaves without children or traps: reuse the boxed emitter's
                // value expression (it only writes `t_n<id> = ...;`).
                self.leaf_boxed(expr, indent);
            }
            ExprKind::Call {
                callee,
                callee_kind,
                args,
            } => {
                for arg in args {
                    self.fast_expr(arg, depth + 1, indent);
                }
                match callee_kind {
                    CalleeKind::Fn => {
                        let (params, _) = self.fn_types(callee);
                        let call_args = args
                            .iter()
                            .zip(&params)
                            .map(|(arg, ty)| self.convert(arg, Repr::of(ty)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        let frames = depth + 2;
                        self.line(
                            indent,
                            &format!("aleph_fast_call_enter(&L_n{id}, {frames});"),
                        );
                        self.assign(indent, id, &format!("aleph_fn_{callee}({call_args})"));
                        self.line(indent, &format!("aleph_fast_call_leave({frames});"));
                    }
                    CalleeKind::Ctor => {
                        if args.is_empty() {
                            self.assign(
                                indent,
                                id,
                                &format!("aleph_record(&RI_{callee}, NULL, 0)"),
                            );
                        } else {
                            self.assign(indent, id, &format!("aleph_list_new({})", args.len()));
                            for (index, arg) in args.iter().enumerate() {
                                let value = self.boxed_temp(arg);
                                self.line(
                                    indent,
                                    &format!("t_n{id}.u.list->items[{index}] = {value};"),
                                );
                            }
                            self.assign(
                                indent,
                                id,
                                &format!(
                                    "aleph_record(&RI_{callee}, t_n{id}.u.list->items, {})",
                                    args.len()
                                ),
                            );
                        }
                    }
                    CalleeKind::Builtin => {
                        let call_args = args
                            .iter()
                            .map(|arg| self.boxed_temp(arg))
                            .collect::<Vec<_>>()
                            .join(", ");
                        let runtime = self.builtin_c_name(callee, expr);
                        let call = repr.unbox(&format!("aleph_b_{runtime}({call_args})"));
                        self.line(indent, &format!("aleph_here(&L_n{id});"));
                        if calls_back(callee) {
                            let frames = depth + 1;
                            self.line(indent, &format!("aleph_g_eval_depth += {frames};"));
                            self.assign(indent, id, &call);
                            self.line(indent, &format!("aleph_g_eval_depth -= {frames};"));
                        } else {
                            self.assign(indent, id, &call);
                        }
                    }
                }
            }
            ExprKind::BinOp { op, lhs, rhs } => {
                self.fast_expr(lhs, depth + 1, indent);
                match op {
                    BinOp::And | BinOp::Or => {
                        let left = Self::temp(lhs);
                        let condition = if *op == BinOp::And {
                            format!("!{left}")
                        } else {
                            left.clone()
                        };
                        self.line(indent, &format!("if ({condition}) {{"));
                        self.assign(indent + 1, id, &left);
                        self.line(indent, "} else {");
                        self.fast_expr(rhs, depth + 1, indent + 1);
                        self.assign(indent + 1, id, &Self::temp(rhs));
                        self.line(indent, "}");
                    }
                    _ => {
                        self.fast_expr(rhs, depth + 1, indent);
                        self.fast_binop(expr, *op, lhs, rhs, indent);
                    }
                }
            }
            ExprKind::UnOp { op, operand } => {
                self.fast_expr(operand, depth + 1, indent);
                let value = Self::temp(operand);
                match (op, self.repr(operand)) {
                    (UnOp::Not, _) => self.assign(indent, id, &format!("!{value}")),
                    (UnOp::Neg, Repr::F64) => self.assign(indent, id, &format!("-{value}")),
                    (UnOp::Neg, Repr::I64) => {
                        self.line(indent, &format!("aleph_here(&L_n{id});"));
                        self.assign(indent, id, &format!("aleph_fast_neg({value})"));
                    }
                    (UnOp::Neg, _) => {
                        self.fail_internal(expr, "internal compiler error: non-numeric negation");
                    }
                }
            }
            ExprKind::If { cond, then_, else_ } => {
                self.fast_expr(cond, depth + 1, indent);
                self.line(indent, &format!("if ({}) {{", Self::temp(cond)));
                self.fast_expr(then_, depth + 1, indent + 1);
                let then_value = self.convert(then_, repr);
                self.assign(indent + 1, id, &then_value);
                self.line(indent, "} else {");
                self.fast_expr(else_, depth + 1, indent + 1);
                let else_value = self.convert(else_, repr);
                self.assign(indent + 1, id, &else_value);
                self.line(indent, "}");
            }
            ExprKind::List { elems } => {
                if literal_list_items(expr).is_some() {
                    self.assign(
                        indent,
                        id,
                        &format!("aleph_list(aleph_list_n{id}, {})", elems.len()),
                    );
                } else {
                    for elem in elems {
                        self.fast_expr(elem, depth + 1, indent);
                    }
                    self.assign(indent, id, &format!("aleph_list_new({})", elems.len()));
                    for (index, elem) in elems.iter().enumerate() {
                        let value = self.boxed_temp(elem);
                        self.line(
                            indent,
                            &format!("t_n{id}.u.list->items[{index}] = {value};"),
                        );
                    }
                }
            }
            ExprKind::Field { name, value } => {
                self.fast_expr(value, depth + 1, indent);
                let index = self.field_index(value, name);
                let field = format!("{}.u.rec->fields[{index}]", Self::temp(value));
                self.assign(indent, id, &repr.unbox(&field));
            }
            ExprKind::Some { value } | ExprKind::Ok { value } | ExprKind::Err { value } => {
                self.fast_expr(value, depth + 1, indent);
                let constructor = match &expr.kind {
                    ExprKind::Some { .. } => "aleph_some",
                    ExprKind::Ok { .. } => "aleph_ok",
                    _ => "aleph_err",
                };
                let inner = self.boxed_temp(value);
                self.assign(indent, id, &format!("{constructor}({inner})"));
            }
            ExprKind::Try { value } => {
                self.fast_expr(value, depth + 1, indent);
                let base = Self::temp(value);
                self.line(indent, &format!("if ({base}.tag == AL_OK) {{"));
                self.assign(indent + 1, id, &repr.unbox(&format!("{base}.u.box->value")));
                self.line(indent, "} else {");
                self.line(indent + 1, &format!("aleph_ret_ = {base};"));
                self.line(indent + 1, "goto L_epilogue;");
                self.line(indent, "}");
            }
            ExprKind::Else { value, default } => {
                self.fast_expr(value, depth + 1, indent);
                let tag = self.else_tag(value);
                let base = Self::temp(value);
                self.line(indent, &format!("if ({base}.tag == {tag}) {{"));
                self.assign(indent + 1, id, &repr.unbox(&format!("{base}.u.box->value")));
                self.line(indent, "} else {");
                self.fast_expr(default, depth + 1, indent + 1);
                let fallback = self.convert(default, repr);
                self.assign(indent + 1, id, &fallback);
                self.line(indent, "}");
            }
            ExprKind::Has { value } | ExprKind::IsOk { value } => {
                self.fast_expr(value, depth + 1, indent);
                let tag = if matches!(expr.kind, ExprKind::Has { .. }) {
                    "AL_SOME"
                } else {
                    "AL_OK"
                };
                self.assign(indent, id, &format!("{}.tag == {tag}", Self::temp(value)));
            }
            ExprKind::Lam { .. } => self.closure(expr, true, indent),
            ExprKind::Match { value, arms } => {
                self.fast_expr(value, depth + 1, indent);
                for (index, arm) in arms.iter().enumerate() {
                    self.match_arm_open(value, arms.len(), index, &arm.variant, indent);
                    let fields = self
                        .checked
                        .records
                        .get(&arm.variant)
                        .cloned()
                        .unwrap_or_default();
                    for (k, (binder, (_, ty))) in arm.binders.iter().zip(&fields).enumerate() {
                        let binder_repr = Repr::of(ty);
                        let field = format!("{}.u.rec->fields[{k}]", Self::temp(value));
                        self.line(
                            indent + 1,
                            &format!(
                                "{} l_{binder} = {}; (void)l_{binder};",
                                binder_repr.c_type(),
                                binder_repr.unbox(&field)
                            ),
                        );
                    }
                    self.fast_expr(&arm.body, depth + 1, indent + 1);
                    let body = self.convert(&arm.body, repr);
                    self.assign(indent + 1, id, &body);
                }
                self.line(indent, "}");
            }
        }
    }

    /// The temp of `expr` converted to `target` (boxing or unboxing).
    fn convert(&self, expr: &Expr, target: Repr) -> String {
        let from = self.repr(expr);
        let temp = Self::temp(expr);
        if from == target {
            temp
        } else if target == Repr::Boxed {
            from.boxed(&temp)
        } else {
            target.unbox(&from.boxed(&temp))
        }
    }

    /// Childless boxed leaves: the same value expression as the slow emitter.
    fn leaf_boxed(&mut self, expr: &Expr, indent: usize) {
        let id = expr.id.0;
        let value = match &expr.kind {
            ExprKind::Str { value } => {
                format!("aleph_str_n({}, {})", c_string(value), value.len())
            }
            ExprKind::Nil => "aleph_unit()".to_string(),
            ExprKind::FnRef { name } => {
                let label = self.ref_info(name).kind.label();
                format!("aleph_fnval_static(&aleph_fnref_{label}_{name})")
            }
            ExprKind::Empty { .. } | ExprKind::EmptyList => "aleph_list_new(0)".to_string(),
            ExprKind::Dict { .. } => "aleph_dict_empty()".to_string(),
            ExprKind::None { .. } => "aleph_none()".to_string(),
            _ => unreachable!("leaf_boxed only handles childless boxed leaves"),
        };
        self.assign(indent, id, &value);
    }

    fn fast_binop(&mut self, expr: &Expr, op: BinOp, lhs: &Expr, rhs: &Expr, indent: usize) {
        let id = expr.id.0;
        let left = Self::temp(lhs);
        let right = Self::temp(rhs);
        let operands = self.repr(lhs);
        let symbol = match op {
            BinOp::Add => "+",
            BinOp::Sub => "-",
            BinOp::Mul => "*",
            BinOp::Div => "/",
            BinOp::Mod => "%",
            BinOp::Eq => "==",
            BinOp::Ne => "!=",
            BinOp::Lt => "<",
            BinOp::Le => "<=",
            BinOp::Gt => ">",
            BinOp::Ge => ">=",
            BinOp::And | BinOp::Or => unreachable!("handled by fast_expr"),
        };
        match op {
            BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div | BinOp::Mod => match operands {
                Repr::F64 if op != BinOp::Mod => {
                    self.assign(indent, id, &format!("{left} {symbol} {right}"));
                }
                Repr::I64 => {
                    let function = match op {
                        BinOp::Add => "aleph_fast_add",
                        BinOp::Sub => "aleph_fast_sub",
                        BinOp::Mul => "aleph_fast_mul",
                        BinOp::Div => "aleph_fast_div",
                        _ => "aleph_fast_mod",
                    };
                    self.line(indent, &format!("aleph_here(&L_n{id});"));
                    self.assign(indent, id, &format!("{function}({left}, {right})"));
                }
                _ => self.fail_internal(expr, "internal compiler error: non-numeric arithmetic"),
            },
            BinOp::Eq | BinOp::Ne => {
                if operands == Repr::Boxed || self.repr(rhs) == Repr::Boxed {
                    let negate = if op == BinOp::Ne { "!" } else { "" };
                    let value = format!(
                        "{negate}aleph_values_equal({}, {})",
                        self.boxed_temp(lhs),
                        self.boxed_temp(rhs)
                    );
                    self.assign(indent, id, &value);
                } else {
                    // IEEE `==` for f64 (NaN != NaN, -0.0 == 0.0), as in
                    // aleph_values_equal.
                    self.assign(indent, id, &format!("{left} {symbol} {right}"));
                }
            }
            _ => match operands {
                // IEEE comparisons: all false when either side is NaN.
                Repr::I64 | Repr::F64 => {
                    self.assign(indent, id, &format!("{left} {symbol} {right}"));
                }
                _ => {
                    let function = match op {
                        BinOp::Lt => "aleph_lt",
                        BinOp::Le => "aleph_le",
                        BinOp::Gt => "aleph_gt",
                        _ => "aleph_ge",
                    };
                    let value = format!(
                        "{function}({}, {})",
                        self.boxed_temp(lhs),
                        self.boxed_temp(rhs)
                    );
                    self.assign(indent, id, &value);
                }
            },
        }
    }
}

/// Lambdas (ADR-0037): each `lam` is lifted to `aleph_lam_n<id>` (the
/// `AlFn` code: fast body, depth accounting of `interp::call_lam`) plus a cold
/// instrumented `aleph_lamslow_n<id>`. Captured values live in the `AlFn`.
impl<'a> Generator<'a> {
    /// Every `lam` in compiled code (examples are not compiled), pre-order.
    fn lambdas(&self) -> Vec<&'a Expr> {
        let mut found = Vec::new();
        for function in &self.file.fns {
            for root in frame_roots(function) {
                ast::walk_expr(root, &mut |expr| {
                    if matches!(expr.kind, ExprKind::Lam { .. }) {
                        found.push(expr);
                    }
                });
            }
        }
        found
    }

    /// Outer names the body of `lam` reads, sorted, with their types. Names
    /// bound inside the body (its binders, nested binders, match binders) are
    /// not captured; T005 keeps them distinct from every visible outer name.
    fn captures(&self, lam: &Expr) -> Vec<(String, Type)> {
        let ExprKind::Lam { binders, body } = &lam.kind else {
            unreachable!("captures of a non-lambda");
        };
        let mut bound: BTreeSet<&str> = binders.iter().map(String::as_str).collect();
        let mut reads = std::collections::BTreeMap::new();
        ast::walk_expr(body, &mut |expr| match &expr.kind {
            ExprKind::Lam { binders, .. } => bound.extend(binders.iter().map(String::as_str)),
            ExprKind::Match { arms, .. } => {
                for arm in arms {
                    bound.extend(arm.binders.iter().map(String::as_str));
                }
            }
            ExprKind::Var { name } => {
                let ty = self.checked.expr_types.get(&expr.id).cloned();
                reads.entry(name.clone()).or_insert(ty);
            }
            _ => {}
        });
        reads
            .into_iter()
            .filter(|(name, _)| !bound.contains(name.as_str()))
            .map(|(name, ty)| (name, ty.unwrap_or(Type::Error)))
            .collect()
    }

    /// Evaluate a `lam` node: an arena `AlFn` holding the captured values.
    fn closure(&mut self, lam: &Expr, fast: bool, indent: usize) {
        let id = lam.id.0;
        let captures = self.captures(lam);
        if captures.is_empty() {
            // Nothing captured: one static value, no arena allocation per evaluation.
            self.line(indent, "{");
            self.line(
                indent + 1,
                &format!(
                    "static const AlFn aleph_lamref_ = {{aleph_lam_n{id}, \"lam\", AL_FN_LAM, NULL, 0}};"
                ),
            );
            self.assign(indent + 1, id, "aleph_fnval_static(&aleph_lamref_)");
            self.line(indent, "}");
            return;
        }
        let values = captures
            .iter()
            .map(|(name, ty)| {
                let local = format!("l_{name}");
                if fast {
                    Repr::of(ty).boxed(&local)
                } else {
                    local
                }
            })
            .collect::<Vec<_>>()
            .join(", ");
        let count = captures.len();
        self.line(indent, "{");
        self.line(
            indent + 1,
            &format!("AlValue aleph_cap_[{count}] = {{{values}}};"),
        );
        self.assign(
            indent + 1,
            id,
            &format!("aleph_fnval_lam(aleph_lam_n{id}, aleph_cap_, {count})"),
        );
        self.line(indent, "}");
    }

    /// Binder and captured locals of a lifted lambda, in `repr` form.
    fn lambda_locals(&mut self, lam: &Expr, fast: bool) {
        let ExprKind::Lam { binders, .. } = &lam.kind else {
            unreachable!("locals of a non-lambda");
        };
        let params = match self.checked.expr_types.get(&lam.id) {
            Some(Type::Fn(params, _)) => params.clone(),
            _ => {
                self.fail_internal(lam, "internal compiler error: untyped lambda");
                return;
            }
        };
        let repr = |ty: &Type| if fast { Repr::of(ty) } else { Repr::Boxed };
        for (index, (binder, ty)) in binders.iter().zip(&params).enumerate() {
            let repr = repr(ty);
            let value = repr.unbox(&format!("aleph_args[{index}]"));
            self.line(
                1,
                &format!("{} l_{binder} = {value}; (void)l_{binder};", repr.c_type()),
            );
        }
        let captures = self.captures(lam);
        if captures.is_empty() {
            self.line(1, "(void)aleph_self;");
        }
        for (index, (name, ty)) in captures.iter().enumerate() {
            let repr = repr(ty);
            let value = repr.unbox(&format!("aleph_self->captured[{index}]"));
            self.line(1, &format!("{} l_{name} = {value};", repr.c_type()));
        }
    }

    fn lambda(&mut self, lam: &'a Expr) {
        let ExprKind::Lam { body, .. } = &lam.kind else {
            unreachable!("lifting a non-lambda");
        };
        let id = lam.id.0;
        let mut declarations = Vec::new();
        frame_nodes(body, &mut declarations);

        // Instrumented body: mirrors `interp::eval` node by node.
        self.line(0, &lam_slow_signature(id));
        self.line(0, "{");
        self.lambda_locals(lam, false);
        self.slow_declarations(declarations.clone());
        self.emit_expr(body, 0, 1);
        self.line(1, &format!("return t_n{};", body.id.0));
        self.line(0, "}");
        self.out.push('\n');

        // Entry: `call_lam` accounting, then the fast body when it cannot
        // reach the evaluation limit (ADR-0027), else the slow body.
        self.line(0, &lam_signature(id));
        self.line(0, "{");
        self.lambda_locals(lam, true);
        self.fast_declarations(declarations);
        self.line(1, "AlValue aleph_ret_;");
        self.line(1, "(void)aleph_n;");
        self.line(1, "aleph_lam_enter();");
        // One region for both bodies (ADR-0039): binders and captured values
        // are older than the mark, and map/filter/fold/map2 store the result
        // only after the call returns.
        let region = self.may_allocate(&[body]);
        if region {
            self.line(1, "AlMark aleph_mark_ = aleph_region_mark();");
        }
        let max_depth = expr_max_depth(body);
        self.line(
            1,
            &format!("if (AL_UNLIKELY(!aleph_fast_ok({max_depth}))) {{"),
        );
        self.line(
            2,
            &format!("aleph_ret_ = aleph_lamslow_n{id}(aleph_self, aleph_args);"),
        );
        self.line(1, "} else {");
        self.line(2, "aleph_loc_push();");
        self.fast_expr(body, 0, 2);
        let value = self.boxed_temp(body);
        self.line(2, &format!("aleph_ret_ = {value};"));
        self.line(2, "aleph_loc_pop();");
        self.line(1, "}");
        if region {
            self.line(
                1,
                "aleph_ret_ = aleph_region_exit(aleph_mark_, aleph_ret_);",
            );
        }
        self.line(1, "aleph_lam_leave();");
        self.line(1, "return aleph_ret_;");
        self.line(0, "}");
        self.out.push('\n');
    }

    fn slow_declarations(&mut self, mut ids: Vec<NodeId>) {
        ids.sort_unstable_by_key(|id| id.0);
        for id in ids {
            self.line(1, &format!("AlValue t_n{};", id.0));
        }
    }

    fn fast_declarations(&mut self, mut ids: Vec<NodeId>) {
        ids.sort_unstable_by_key(|id| id.0);
        for id in ids {
            let repr = self.repr_of_id(id);
            self.line(1, &format!("{} t_n{};", repr.c_type(), id.0));
        }
    }
}

/// `code` with the contents of every C string literal removed (escapes kept
/// paired, so `\"` does not end a literal).
fn without_string_literals(code: &str) -> String {
    let mut out = String::with_capacity(code.len());
    let mut chars = code.chars();
    let mut in_string = false;
    while let Some(c) = chars.next() {
        if in_string {
            match c {
                '\\' => {
                    chars.next();
                }
                '"' => {
                    in_string = false;
                    out.push(c);
                }
                _ => {}
            }
        } else {
            if c == '"' {
                in_string = true;
            }
            out.push(c);
        }
    }
    out
}

/// The C identifiers that follow each `prefix` in `code` (`&L_n12` -> `12`).
fn used_names<'c>(code: &'c str, prefix: &str) -> BTreeSet<&'c str> {
    code.split(prefix)
        .skip(1)
        .map(|rest| {
            let end = rest
                .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .unwrap_or(rest.len());
            &rest[..end]
        })
        .collect()
}

fn function_needs_epilogue(function: &ast::Fn) -> bool {
    if function
        .stmts
        .iter()
        .any(|stmt| matches!(stmt.kind, StmtKind::Guard { .. }))
    {
        return true;
    }
    let mut found = false;
    let mut visit = |expr: &Expr| {
        if matches!(expr.kind, ExprKind::Try { .. }) {
            found = true;
        }
    };
    for stmt in &function.stmts {
        match &stmt.kind {
            StmtKind::Let { value, .. } | StmtKind::Do { value } => {
                ast::walk_expr(value, &mut visit);
            }
            StmtKind::Guard { cond, value } => {
                ast::walk_expr(cond, &mut visit);
                ast::walk_expr(value, &mut visit);
            }
        }
    }
    ast::walk_expr(&function.result, &mut visit);
    found
}

fn function_declarations(function: &ast::Fn) -> Vec<NodeId> {
    let mut declarations = Vec::new();
    for root in frame_roots(function) {
        frame_nodes(root, &mut declarations);
    }
    declarations
}

fn lam_signature(id: u32) -> String {
    format!("static AlValue aleph_lam_n{id}(const AlFn *aleph_self, AlValue *aleph_args, size_t aleph_n)")
}

fn lam_slow_signature(id: u32) -> String {
    format!("static AlValue aleph_lamslow_n{id}(const AlFn *aleph_self, AlValue *aleph_args)")
}

fn arg_list(args: &[Expr]) -> String {
    args.iter()
        .map(|arg| format!("t_n{}", arg.id.0))
        .collect::<Vec<_>>()
        .join(", ")
}

fn int_literal(value: i64) -> String {
    if value == i64::MIN {
        "INT64_MIN".to_string()
    } else if value < 0 {
        format!("-INT64_C({})", value.unsigned_abs())
    } else {
        format!("INT64_C({value})")
    }
}

/// Escape a Rust string as a C string literal.
///
/// Non-ASCII and control bytes use three-digit octal escapes, and every `?` is
/// escaped so a pair of them can never form a trigraph.
fn c_string(value: &str) -> String {
    let mut text = String::with_capacity(value.len() + 2);
    text.push('"');
    for &byte in value.as_bytes() {
        match byte {
            b'"' => text.push_str("\\\""),
            b'\\' => text.push_str("\\\\"),
            b'?' => text.push_str("\\?"),
            0x20..=0x7e => text.push(byte as char),
            _ => {
                let _ = write!(text, "\\{byte:03o}");
            }
        }
    }
    text.push('"');
    text
}

